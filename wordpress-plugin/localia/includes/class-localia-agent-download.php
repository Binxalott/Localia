<?php
/**
 * "Download the agent" button: zips the bundled desktop agent together with a config
 * file holding this site's connection details, so setup is download, unzip, run.
 *
 * @package Localia
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

class Localia_Agent_Download {

	const ACTION = 'localia_download_agent';

	public static function init() {
		add_action( 'admin_post_' . self::ACTION, array( __CLASS__, 'download' ) );
	}

	public static function available() {
		return class_exists( 'ZipArchive' ) && is_dir( LOCALIA_DIR . 'agent' );
	}

	public static function url() {
		return wp_nonce_url( admin_url( 'admin-post.php?action=' . self::ACTION ), self::ACTION );
	}

	public static function download() {
		if ( ! current_user_can( 'manage_options' ) ) {
			wp_die( esc_html__( 'You are not allowed to do that.', 'localia' ), 403 );
		}
		check_admin_referer( self::ACTION );
		if ( ! self::available() ) {
			wp_die( esc_html__( 'This server cannot create zip files. Use the pairing code on the Settings page instead.', 'localia' ) );
		}

		$tmp = wp_tempnam( 'localia-agent' );
		$zip = new ZipArchive();
		if ( true !== $zip->open( $tmp, ZipArchive::OVERWRITE ) ) {
			wp_die( esc_html__( 'Could not create the zip file.', 'localia' ) );
		}

		$root  = LOCALIA_DIR . 'agent/';
		$files = new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $root, FilesystemIterator::SKIP_DOTS ) );
		foreach ( $files as $file ) {
			$path     = wp_normalize_path( $file->getPathname() );
			$relative = substr( $path, strlen( wp_normalize_path( $root ) ) );
			if ( 'js/config.js' === $relative ) {
				continue;
			}
			$name = 'localia-agent/' . $relative;
			$zip->addFile( $path, $name );
			if ( preg_match( '/\.(sh|command)$/', $relative ) ) {
				// Keep the start scripts executable on macOS/Linux.
				$zip->setExternalAttributesName( $name, ZipArchive::OPSYS_UNIX, 0100755 << 16 );
			}
		}

		$preset = wp_json_encode( Localia_Settings::pairing(), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE );
		$zip->addFromString(
			'localia-agent/js/config.js',
			"// Connection details for your WordPress site. Keep this file private: it contains your secret.\n" .
			"// Generated by the Localia plugin. Downloading the agent again after \"Regenerate secret\" replaces it.\n" .
			'window.LOCALIA_PRESET = ' . $preset . ";\n"
		);
		$zip->addFromString( 'localia-agent/START HERE.txt', self::readme() );
		$zip->close();

		nocache_headers();
		header( 'Content-Type: application/zip' );
		header( 'Content-Disposition: attachment; filename="localia-agent.zip"' );
		header( 'Content-Length: ' . filesize( $tmp ) );
		header( 'X-Content-Type-Options: nosniff' );
		readfile( $tmp ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_readfile -- streaming a temp file.
		wp_delete_file( $tmp );
		exit;
	}

	private static function readme() {
		$site = wp_specialchars_decode( get_bloginfo( 'name' ), ENT_QUOTES );
		return "Localia agent for: {$site}\r\n" .
			"=====================================\r\n\r\n" .
			"This small app runs on your home PC. It picks up writing jobs from your WordPress\r\n" .
			"site, runs them on the AI model installed on this PC, and sends the results back.\r\n\r\n" .
			"1. Install a local AI runtime if you have not already:\r\n" .
			"     Ollama (recommended): https://ollama.com  then run:  ollama pull llama3.1:8b\r\n" .
			"     or LM Studio: start its server and switch on \"Enable CORS\".\r\n\r\n" .
			"2. Start the agent:\r\n" .
			"     Windows: double-click  start-windows.bat\r\n" .
			"     macOS:   double-click  start-macos.command  (first time: right-click > Open)\r\n" .
			"     Linux:   run  ./start-linux.sh\r\n" .
			"   It needs Python 3 or Node.js (most Macs and Linux PCs already have Python).\r\n" .
			"   Your browser opens http://localhost:8787\r\n\r\n" .
			"3. In the agent page, open Settings, pick your model (press Load), Save,\r\n" .
			"   then press Start agent on the Dashboard. The connection to your site is\r\n" .
			"   already filled in.\r\n\r\n" .
			"Leave the browser tab open. Your WordPress dashboard shows the PC as Online.\r\n\r\n" .
			"KEEP THIS FOLDER PRIVATE: js/config.js contains the secret for your site.\r\n" .
			"If it ever leaks, use \"Regenerate secret\" in WordPress and download the agent again.\r\n";
	}
}
